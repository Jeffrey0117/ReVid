// Base for all line icons: lucide-style 24px stroke icons that inherit the
// surrounding text color.
export const Icon = ({ size = 18, className, children, ...props }) => (
    <svg
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth="2"
        strokeLinecap="round"
        strokeLinejoin="round"
        className={className}
        {...props}
    >
        {children}
    </svg>
);
